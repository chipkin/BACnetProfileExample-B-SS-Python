# The stack library's file name when the adapter (which names it) is not there
# to ask - only used to fill in the missing-library message.
FALLBACK_LIBRARY_NAME = "CASBACnetStack_x64_Release.dll" if os.name == "nt" else "libCASBACnetStack_x64_Release.so"


def load_cas_bacnet_stack():
    """Find, load and bind the CAS BACnet Stack. Returns None on success, or
    (missing file, [folders searched]) when it cannot: the adapter's two files
    or the library are in neither the run directory nor the development
    checkout's submodule, or ctypes cannot load the library it found."""
    global bacnet
    try:
        from CASBACnetStackAdapter import libname
        import CASBACnetStackAdapterBindings
    except ImportError:
        # No adapter either (a release has neither): name the library first -
        # it is the part a customer licenses and builds.
        if not any(os.path.isfile(os.path.join(d, FALLBACK_LIBRARY_NAME)) for d in LIBRARY_DIRECTORIES):
            return FALLBACK_LIBRARY_NAME, LIBRARY_DIRECTORIES
        return "CASBACnetStackAdapterBindings.py", ADAPTER_DIRECTORIES
    if libname is None:
        return FALLBACK_LIBRARY_NAME, LIBRARY_DIRECTORIES
    for directory in LIBRARY_DIRECTORIES:
        library_path = os.path.join(directory, libname)
        if os.path.isfile(library_path):
            try:
                CASBACnetStackAdapterBindings.bind(ctypes.CDLL(library_path))
            except (OSError, AttributeError):
                return libname, LIBRARY_DIRECTORIES
            bacnet = CASBACnetStackAdapterBindings
            return None
    return libname, LIBRARY_DIRECTORIES


def main(argv):
    global g_device_instance, g_bacnet_ip_udp_port, g_analog_input_1_value
    global g_firmware_revision, g_sensor_fault_file

    # --- Load the CAS BACnet Stack -------------------------------------------
    # Required before any other BACnetStack_* call, like the C++ edition's
    # LoadBACnetFunctions(). The library is looked for in the run directory
    # (the folder that holds main.py), then in a development checkout's
    # submodules/cas-bacnet-stack/bin/, where building the stack puts it
    # (README.md "Build the CAS BACnet Stack library"). A release of this
    # example does not include it: it is a separately licensed product.
    missing = load_cas_bacnet_stack()

    # --- Command line + version --------------------------------------------
    # --help / --version print and exit, so handle them before we bind a socket.
    # They work without the stack (the banner then says it is not loaded).
    if helper.handle_help_and_version_args(argv, APP_NAME, APP_VERSION):
        return 0
    if missing is not None:
        helper.print_missing_stack_library(*missing)
        return 1

    # g_firmware_revision (Device object property 44) - see its own comment
    # above for why this is the STACK's version, not this example's own (that
    # is Application_Software_Version / APP_VERSION instead). Must happen after
    # the stack loads (these getters are some of the functions it binds) and
    # before the Device object is ever readable.
    g_firmware_revision = "{}.{}.{}.{}".format(
        bacnet.BACnetStack_GetAPIMajorVersion(), bacnet.BACnetStack_GetAPIMinorVersion(),
        bacnet.BACnetStack_GetAPIPatchVersion(), bacnet.BACnetStack_GetAPIBuildVersion())

    port = helper.parse_port_arg(argv, 47808)
    g_device_instance = helper.parse_device_id_arg(argv, g_device_instance)
    helper.print_version(APP_NAME, APP_VERSION)

    # --- Bind the BACnet/IP socket -----------------------------------------
    if not helper.setup_udp(udp, port, NETWORK_PORT_INSTANCE):
        return 1

    # Capture the BACnet/IP addressing the Network Port object will report.
    g_bacnet_ip_udp_port = port
    local = helper.get_local_ipv4()
    g_ip_address[:] = [int(part) for part in local.address.split(".")]
    g_ip_subnet_mask[:] = [int(part) for part in local.netmask.split(".")]

    # --- Register callbacks -------------------------------------------------
    # The transport + time callbacks are shared boilerplate, keyed to the
    # Network Port instance that owns the socket just bound (the stack
    # identifies a link by its Network Port INSTANCE, so the transport
    # callbacks and the start-up I-Am name the one added below).
    helper.register_common_callbacks(udp, NETWORK_PORT_INSTANCE)
    # The property callbacks are specific to this example. Wrap each Python
    # function in the matching ctypes.CFUNCTYPE and keep the wrapper object
    # alive for the life of the process - see cas_example_helper.py's
    # "CALLBACKS MUST BE ROOTED" note; the same rule applies here.
    property_callbacks = [
        (bacnet.BACnetStack_RegisterCallbackGetPropertyReal,
         bacnet.FPCallbackGetPropertyReal(get_property_real)),
        (bacnet.BACnetStack_RegisterCallbackGetPropertyEnumerated,
         bacnet.FPCallbackGetPropertyEnumerated(get_property_enumerated)),
        (bacnet.BACnetStack_RegisterCallbackGetPropertyUnsignedInteger,
         bacnet.FPCallbackGetPropertyUnsignedInteger(get_property_unsigned_integer)),
        (bacnet.BACnetStack_RegisterCallbackGetPropertyCharacterString,
         bacnet.FPCallbackGetPropertyCharacterString(get_property_character_string)),
        (bacnet.BACnetStack_RegisterCallbackGetPropertyBool,
         bacnet.FPCallbackGetPropertyBool(get_property_bool)),
        (bacnet.BACnetStack_RegisterCallbackGetPropertyOctetString,
         bacnet.FPCallbackGetPropertyOctetString(get_property_octet_string)),
    ]
    for register, callback in property_callbacks:
        helper._callback_refs.append(callback)  # rooted for the life of the process
        register(callback)

    # --- Create the device --------------------------------------------------
    if not bacnet.BACnetStack_AddDevice(g_device_instance):
        print(f"Error: Failed to add the Device {g_device_instance}.")
        return 1

    # Enable ReadProperty (DS-RP-B) - the one mandatory service for B-SS.
    # We set it explicitly to make the profile requirement obvious.
    #
    # We deliberately do NOT enable WriteProperty, ReadPropertyMultiple,
    # SubscribeCOV, or any alarm/event service: a Smart Sensor does not
    # require them, so a faithful B-SS example leaves them off.
    if not bacnet.BACnetStack_SetServiceEnabled(g_device_instance, c.SERVICE_READ_PROPERTY, True):
        print("Error: Failed to enable the ReadProperty service.")
        return 1

    # Discovery: Who-Is/I-Am (DM-DDB-B) and Who-Has/I-Have (DM-DOB-B).
    #
    # These need enabling even though the device already ANSWERS them. The
    # stack's service defaults are whoIs + whoHas + readProperty only - iAm
    # and iHave are left False. Who-Is is answered and the start-up I-Am is
    # sent regardless, because neither is gated on the bit; but
    # Protocol_Services_Supported is emitted verbatim from that bitstring, so
    # without these calls the device DOES I-Am and I-Have while telling every
    # client it supports neither. The README claims DM-DDB-B and DM-DOB-B;
    # this is what makes the claim true on the wire.
    if not (bacnet.BACnetStack_SetServiceEnabled(g_device_instance, c.SERVICE_WHO_IS, True) and
            bacnet.BACnetStack_SetServiceEnabled(g_device_instance, c.SERVICE_I_AM, True) and
            bacnet.BACnetStack_SetServiceEnabled(g_device_instance, c.SERVICE_WHO_HAS, True) and
            bacnet.BACnetStack_SetServiceEnabled(g_device_instance, c.SERVICE_I_HAVE, True)):
        print("Error: Failed to enable the discovery services (Who-Is/I-Am, Who-Has/I-Have).")
        return 1

    # --- Add the read-only sensor objects -----------------------------------
    # Every stack setup call returns a bool; a real device should always check
    # it, so this example does too.
    if not bacnet.BACnetStack_AddObject(g_device_instance, c.OBJECT_TYPE_ANALOG_INPUT, ANALOG_INPUT_INSTANCE):
        print(f"Error: Failed to add Analog Input {ANALOG_INPUT_INSTANCE} (Bronze).")
        return 1
    if not bacnet.BACnetStack_AddObject(g_device_instance, c.OBJECT_TYPE_BINARY_INPUT, BINARY_INPUT_INSTANCE):
        print(f"Error: Failed to add Binary Input {BINARY_INPUT_INSTANCE} (Emerald).")
        return 1
    if not bacnet.BACnetStack_AddObject(g_device_instance, c.OBJECT_TYPE_MULTI_STATE_INPUT,
                                        MULTI_STATE_INPUT_INSTANCE):
        print(f"Error: Failed to add Multi-State Input {MULTI_STATE_INPUT_INSTANCE} (Hot Pink).")
        return 1

    # --- Add the Network Port object ----------------------------------------
    # Every BACnet device (Protocol_Revision 17+) must have at least one
    # Network Port object describing the port it talks on. This one is the
    # BACnet/IP application port; it is the lowest layer, so its reference
    # port is "none". networkNumber 0 with quality "unknown" describes a
    # local port that has not learned its network number - the right answer
    # for a device that is not a router and has not been told one.
    if not bacnet.BACnetStack_AddNetworkPortObject(
            g_device_instance, NETWORK_PORT_INSTANCE,
            c.NETWORK_PORT_NETWORK_TYPE_IPV4,
            c.NETWORK_PORT_PROTOCOL_LEVEL_BACNET_APPLICATION,
            0,  # networkNumber: not configured
            c.NETWORK_NUMBER_QUALITY_UNKNOWN,
            c.NETWORK_PORT_REFERENCE_PORT_NONE):
        print("Error: Failed to add Network Port 1 (Vermilion).")
        return 1

    # --- Enable the OPTIONAL properties we choose to expose -----------------
    # The stack automatically enables an object's REQUIRED properties when the
    # object is added (AddObject / AddNetworkPortObject) - so Units, Polarity,
    # Number_Of_States, Out_Of_Service, and the Network Port's BACnet/IP
    # addressing (IP_Address, IP_Subnet_Mask, BACnet_IP_UDP_Port, ...) are
    # already enabled; our Get* callbacks just supply their values. Only
    # OPTIONAL properties need SetPropertyEnabled. State_Text is optional on a
    # Multi-State Input, so we enable it here (and serve it in
    # get_property_character_string).
    #
    # The Device's Description is optional too, and it is an easy one to get
    # wrong: serving it from a Get callback is NOT enough. The stack checks
    # IsPropertyEnabled BEFORE it ever reaches the callbacks, and for an
    # optional property that check falls back to "is it required?" - which is
    # False. So a Description branch in the callback without this enable is
    # DEAD CODE, and the client reads back Error: unknown-property.
    if not bacnet.BACnetStack_SetPropertyEnabled(g_device_instance, c.OBJECT_TYPE_DEVICE,
                                                 g_device_instance, c.PROPERTY_IDENTIFIER_DESCRIPTION, True):
        print("Error: Failed to enable Description on the Device object.")
        return 1
    if not bacnet.BACnetStack_SetPropertyEnabled(g_device_instance, c.OBJECT_TYPE_MULTI_STATE_INPUT,
                                                 MULTI_STATE_INPUT_INSTANCE,
                                                 c.PROPERTY_IDENTIFIER_STATE_TEXT, True):
        print("Error: Failed to enable State_Text on Multi-State Input 1 (Hot Pink).")
        return 1

    # Reliability is optional on an Analog Input; it is how a sensor says its
    # reading cannot be trusted. Enabling it also gives the FAULT bit of
    # Status_Flags its meaning - the stack derives that bit from it.
    if not bacnet.BACnetStack_SetPropertyEnabled(g_device_instance, c.OBJECT_TYPE_ANALOG_INPUT,
                                                 ANALOG_INPUT_INSTANCE, PROPERTY_IDENTIFIER_RELIABILITY, True):
        print("Error: Failed to enable Reliability on Analog Input 1 (Bronze).")
        return 1

    # The Simulation's test-only broken-wire hook (section 2).
    g_sensor_fault_file = os.environ.get(SENSOR_FAULT_FILE_VARIABLE, "")

    # Who-Is is answered automatically. The spec also requires a device to
    # announce itself on start-up, so broadcast an unsolicited I-Am now (to the
    # local subnet broadcast - the Network Port's own network).
    if not helper.send_i_am(g_device_instance, g_bacnet_ip_udp_port, NETWORK_PORT_INSTANCE):
        print("Warning: the start-up I-Am was not sent.")

    print(f"FYI: Device {g_device_instance} (\"{DEVICE_NAME}\") ready. "
          f"Vendor ID {VENDOR_IDENTIFIER}. Press 'h' for help.")

    # --- Graceful Ctrl+C shutdown -------------------------------------------
    running = [True]

    def stop_running(signum, frame):
        running[0] = False  # finish this tick and exit, instead of dying mid-tick

    signal.signal(signal.SIGINT, stop_running)
    if hasattr(signal, "SIGTERM"):
        signal.signal(signal.SIGTERM, stop_running)

    # --- Run the stack ------------------------------------------------------
    # BACnetStack_Tick() processes incoming messages and timers. Call it
    # continuously, step the sensor Simulation beside it, and poll the keyboard
    # for interactive commands. The stack is single-threaded by contract -
    # everything below runs in this one loop.
    try:
        while running[0]:
            bacnet.BACnetStack_Tick()
            sensor_simulation_tick()

            key = helper.poll_key()
            if key == helper.KeyCommand.HELP:
                helper.print_help(APP_NAME, APP_VERSION)
            elif key == helper.KeyCommand.QUIT:
                running[0] = False
            elif key == helper.KeyCommand.ARROW_UP:
                g_analog_input_1_value += 1.1
                print(f"Analog Input 1 (Bronze) = {g_analog_input_1_value:.1f} C")
            elif key == helper.KeyCommand.ARROW_DOWN:
                g_analog_input_1_value -= 1.1
                print(f"Analog Input 1 (Bronze) = {g_analog_input_1_value:.1f} C")

            time.sleep(0.001)  # 1 ms - be a good citizen, don't spin the CPU
    finally:
        helper.restore_input()
        udp.shutdown()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
