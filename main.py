# BACnet Profile Example - B-SS (BACnet Smart Sensor) - Python
#
# This example shows the *minimum* needed to implement the BACnet "B-SS"
# (Smart Sensor) device profile with the CAS BACnet Stack.
#
# "A B-SS is a simple sensing device with very limited resources." (ANSI/ASHRAE
# 135-2024, Annex L.4.5). Its Profile Function is the one Data Sharing line of
# that clause: "Ability to provide values for any of its BACnet objects upon
# request" - a client reads the sensor and gets what it is measuring NOW. Its
# only mandatory service is:
#
#     DS-RP-B  - respond to ReadProperty requests
#
# plus the ability to be discovered: it answers Who-Is with I-Am (handled
# automatically by the stack) and announces itself with an unsolicited I-Am on
# start-up.
#
# SIMULATION. This example has no real sensor, so section 2 below is a sensor
# Simulation that stands in for the physical world: the temperature ramps up
# and down, the binary input toggles and the multi-state input steps through
# its states, all on a timer. It is NOT part of the BACnet Surface - on a real
# device you replace sensor_simulation_tick() with your hardware sampling. The
# Simulation also has one Failure Mode: a broken sensor wire, which this device
# reports the BACnet way, as Reliability OPEN_LOOP and the FAULT bit of
# Status_Flags (cl. 12.2.7, 12.2.9). A Wire Test breaks the "wire" through a
# test-only hook (SENSOR_FAULT_FILE_VARIABLE below); nothing on the network can.
#
# A B-SS does NOT require WriteProperty, COV, alarms/events, scheduling, or
# trending - so this example deliberately does NOT enable any of those. That is
# the whole point of a profile example: implement exactly what the profile
# asks for, nothing more.
#
# This is the Python edition of BACnetProfileExample-B-SS-CPP - same objects,
# same names, same section layout, so you can diff the two side by side. The
# systematic difference is the binding mechanism: Python talks to the native
# CAS BACnet Stack library through `ctypes`, using the stack's own generated
# Python adapter IN PLACE from submodules/cas-bacnet-stack/adapters/python/
# (nothing of it is copied into this repository), which means:
#
#   - an EXPLICIT load step, like the C++ edition's LoadBACnetFunctions():
#     `ctypes.CDLL(<run directory or submodule bin>/<libname>)` then
#     `bind(library)`, both before any BACnetStack_* call (see "Load the CAS
#     BACnet Stack" below). Without the library the example prints why and
#     exits 1.
#   - every Get*Property callback is a plain Python function wrapped in a
#     ctypes.CFUNCTYPE, receiving ctypes POINTER out-parameters it indexes
#     like a list (`value[0] = 21.5`).
#   - THE STACK IS SINGLE-THREADED BY CONTRACT. Nothing in this file spawns a
#     thread that touches the stack; all networking is done through a
#     non-blocking socket (common/simple_udp.py) polled once per
#     BACnetStack_Tick() in the same loop - see "Run the stack" at the bottom.
#
# The device exposes three read-only sensor objects plus the Network Port
# object that every BACnet device must have. Each object is given a colour name
# (a convention shared across this example series):
#
#     Device 389001          "Chipkin Example B-SS"    (instance configurable with --deviceID)
#     Analog Input  1        "Bronze"     (REAL, degrees Celsius; ramps 18.0 .. 26.0)
#     Binary Input  1        "Emerald"    (active / inactive; toggles every 3 s)
#     Multi-State Input 1    "Hot Pink"   (an enumerated state, 1..3; steps every 4 s)
#     Network Port 1         "Vermilion"  (the BACnet/IP port - required)
#
# To be a conformant BACnet device (Protocol_Revision 30) each object must
# expose its full set of REQUIRED properties. Most are generated by the stack
# (Object_Identifier, Object_Type, Status_Flags, Object_List, Protocol_*).
# Event_State is NOT generated - with no alarming configured it simply reads its
# datatype default of normal(0), correct by coincidence, not because the stack
# computes it. The handful that the application must supply are served by the
# Get*Property callbacks below, and a few are turned on with SetPropertyEnabled.
#
# Interactive keys (handled by the shared helper): h = help, q = quit,
# up/down = nudge the simulated Analog Input 1 reading by +/-1.1. Command line:
# --port <n>, --deviceID <n>.
#
# All the UDP/stack plumbing lives in common/ so this file can stay focused on
# the BACnet logic.
# =============================================================================

